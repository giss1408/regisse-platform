#!/usr/bin/env bash
# Builds a product's `.env.platform` from what the platform already knows, so nobody copies secrets by hand:
#   infra/secrets/<name>.env          database, redis, public host (written by new-product.sh)
#   infra/secrets/<name>.hooks.env    the number-change hook key (written by wire-hooks.sh), optional
#   infra/secrets/<name>.generated.env  secrets this script generated (`KEY=@random` in the defaults file), created once and kept
#   --defaults <file>                 the product's own settings; ${VAR} is expanded from the files above and from
#                                     URL_SCHEME, PORT_SUFFIX (from infra/.env) and SERVICE_KEY (the product's key in auth/.env.platform)
# usage: make-product-env.sh <name> <dest> --defaults <file>        (re-running keeps every generated secret; the output is mode 600)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SECRETS="${SECRETS_DIR:-$ROOT/infra/secrets}"
INFRA_ENV="${INFRA_ENV:-$ROOT/infra/.env}"
AUTH_ENV="${AUTH_ENV:-$ROOT/auth/.env.platform}"
name="${1:-}"; dest="${2:-}"; shift 2 || true
defaults=""
while [ $# -gt 0 ]; do case "$1" in --defaults) defaults="${2:-}"; shift 2 ;; *) echo "unknown arg $1" >&2; exit 2 ;; esac; done
[ -n "$name" ] && [ -n "$dest" ] && [ -f "$defaults" ] || { echo "usage: $0 <name> <dest> --defaults <file>" >&2; exit 2; }
[ -f "$SECRETS/$name.env" ] || { echo "$SECRETS/$name.env not found: run infra/scripts/new-product.sh $name first" >&2; exit 1; }
umask 077
touch "$SECRETS/$name.generated.env"; chmod 600 "$SECRETS/$name.generated.env"
python3 - "$name" "$dest" "$defaults" "$SECRETS" "$INFRA_ENV" "$AUTH_ENV" <<'PY'
import json, os, secrets, string, sys
name, dest, defaults, secdir, infra_env, auth_env = sys.argv[1:7]

def read(path):
    out = {}
    if os.path.exists(path):
        for line in open(path).read().splitlines():
            if line.strip() and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v
    return out

base = read(f"{secdir}/{name}.env")          # DATABASE_URL, REDIS_URL, PUBLIC_HOST
hooks = read(f"{secdir}/{name}.hooks.env")   # <PRODUCT>_AUTH_HOOK_KEY
gen = read(f"{secdir}/{name}.generated.env")
infra = read(infra_env)
scheme = infra.get("SITE_SCHEME") or "https://"
port = infra.get("HTTP_PORT", "80")
ctx = {**infra, **base, "URL_SCHEME": scheme, "PORT_SUFFIX": f":{port}" if scheme.startswith("http://") and port != "80" else ""}
try:
    ak = read(auth_env).get("AUTH_SERVICE_KEYS_JSON")
    ctx["SERVICE_KEY"] = json.loads(ak).get(name, "") if ak else ""
except ValueError:
    ctx["SERVICE_KEY"] = ""

lines = [(k, v) for k, v in base.items()] + [(k, v) for k, v in hooks.items()]
newly = {}
for raw in open(defaults).read().splitlines():
    if not raw.strip() or raw.startswith("#") or "=" not in raw:
        continue
    k, v = raw.split("=", 1)
    v = v.split("  #")[0].rstrip()
    if v.startswith("@random"):
        if k not in gen:
            gen[k] = newly[k] = secrets.token_hex(32)
        v = gen[k]
    else:
        v = string.Template(v).safe_substitute(ctx)
    lines.append((k, v))
if newly:
    with open(f"{secdir}/{name}.generated.env", "a") as f:
        for k, v in newly.items():
            f.write(f"{k}={v}\n")
seen, out = set(), []
for k, v in lines:            # a later definition (the product's own settings) wins over the platform's
    seen.add(k)
latest = {}
for k, v in lines:
    latest[k] = v
with open(dest, "w") as f:
    f.write(f"# Generated by make-product-env.sh for '{name}'. Do not edit by hand, do not commit: re-run the script.\n")
    for k, v in latest.items():
        f.write(f"{k}={v}\n")
os.chmod(dest, 0o600)
missing = [k for k, v in latest.items() if v == "" or "${" in v]
print(f"{dest}: {len(latest)} settings" + (f"; EMPTY OR UNRESOLVED: {', '.join(missing)}" if missing else ""))
PY
