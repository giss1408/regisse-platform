#!/usr/bin/env bash
# Provision a product on the shared infra: Postgres role+db, Redis ACL user + DB index, Caddy route, secrets file.
# usage: new-product.sh <name> [--postgis] [--upstream host:port]
# Idempotent per name: refuses to overwrite an existing product (delete its secrets file deliberately first).
set -euo pipefail
cd "$(dirname "$0")/.."

name="${1:-}"; shift || true
[[ "$name" =~ ^[a-z][a-z0-9]{1,24}$ ]] || { echo "name must match ^[a-z][a-z0-9]{1,24}$ (no underscores/hyphens: used in role, db and host names)"; exit 2; }
postgis=0; upstream="${name}-web:8000"; max_body=""; admin_ips=""; caddy_only=0
while [ $# -gt 0 ]; do
  case "$1" in
    --postgis) postgis=1 ;;
    --upstream) upstream="$2"; shift ;;
    --max-body) max_body="$2"; shift ;;      # e.g. 6MB: Caddy answers 413 above it, before the app sees the body
    --admin-ips) admin_ips="$2"; shift ;;    # space-separated IPs/CIDRs allowed to open /admin/* (optional; see global.d/cloudflare.caddy.example)
    --caddy-only) caddy_only=1 ;;            # print the Caddy snippet and exit (no database, no files): for review and tests
    *) echo "unknown arg $1"; exit 2 ;;
  esac; shift
done

set -a; source .env; set +a

caddy_snippet() {
  cat <<CADDY
${SITE_SCHEME:-}${name}-api.${DOMAIN} {
	encode zstd gzip
$( [ -n "$max_body" ] && printf '\t# A body whose declared size is over the limit is refused with 413 at once; request_body also cuts off chunked bodies that grow past it.\n\t@too_large expression `{http.request.header.Content-Length}.size() > 0 && int({http.request.header.Content-Length}) > %s`\n\trespond @too_large "Request too large" 413\n\trequest_body {\n\t\tmax_size %s\n\t}\n' "$(python3 -c "import re,sys;m=re.fullmatch(r'(\\d+)\\s*([KMG]?B)',sys.argv[1],re.I);u={'B':1,'KB':1024,'MB':1048576,'GB':1073741824};print(int(m.group(1))*u[m.group(2).upper()])" "$max_body")" "$max_body" )
	# Private routes (called by the auth service, and /metrics scraped by the monitoring agent, over the private network) are not published on the public hostname.
	@private path /internal/* /api/internal/* /metrics /metrics/*
	respond @private 404
$( [ -n "$admin_ips" ] && printf '\t# The low-level admin only from these addresses (client_ip is the real client behind Cloudflare once the trusted ranges are configured).\n\t@admin_blocked {\n\t\tpath /admin/*\n\t\tnot client_ip %s\n\t}\n\trespond @admin_blocked "Forbidden" 403\n' "$admin_ips" )
	reverse_proxy ${upstream} {
		health_uri /healthz
		health_interval 5s
		health_passes 1
		health_headers {
			Host ${name}-api.${DOMAIN}
			X-Forwarded-Proto https
		}
	}
}
CADDY
}
if [ "$caddy_only" = 1 ]; then caddy_snippet; exit 0; fi

secret="secrets/$name.env"
[ ! -f "$secret" ] || { echo "product '$name' already exists ($secret)"; exit 1; }

PSQL() { docker compose exec -T -e PGPASSWORD="$POSTGRES_PASSWORD" postgres psql -v ON_ERROR_STOP=1 -U postgres "$@"; }
RCLI() { docker compose exec -T redis redis-cli --no-auth-warning -a "$REDIS_ADMIN_PASSWORD" "$@"; }

dbname="db_$name"; role="role_$name"
pw=$(openssl rand -hex 24)
rpw=$(openssl rand -hex 24)

# Redis DB index: next free number (0 is reserved for infra checks)
# (the next number after the highest one a product already uses: counting files breaks as soon as other files, like hooks.env, live in secrets/)
idx=$(( $(cat secrets/*.env 2>/dev/null | grep -E '^REDIS_URL=' | sed -E 's#.*/([0-9]+)$#\1#' | sort -n | tail -1 | grep -E '^[0-9]+$' || echo 0) + 1 ))
[ "$idx" -le 15 ] || { echo "no free Redis DB index (max 15 products); use key prefixes or a second Redis"; exit 1; }

PSQL -d postgres <<SQL
CREATE ROLE $role LOGIN PASSWORD '$pw' CONNECTION LIMIT 30;
ALTER ROLE $role SET statement_timeout = '30s';
ALTER ROLE $role SET idle_in_transaction_session_timeout = '60s';
CREATE DATABASE $dbname OWNER $role;
REVOKE ALL ON DATABASE $dbname FROM PUBLIC;
SQL
PSQL -d "$dbname" <<SQL
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT ALL ON SCHEMA public TO $role;
SQL
[ "$postgis" = 1 ] && PSQL -d "$dbname" -c "CREATE EXTENSION IF NOT EXISTS postgis;" >/dev/null

# Redis: dedicated user restricted from dangerous/admin commands (no FLUSHALL, KEYS, CONFIG...), own DB index via URL.
RCLI ACL SETUSER "$name" on ">$rpw" '~*' '&*' '+@all' '-@dangerous' '-@admin' '+flushdb' >/dev/null
RCLI ACL SAVE >/dev/null

# Caddy route
caddy_snippet > "conf.d/$name.caddy"
docker compose exec -T caddy caddy reload --config /etc/caddy/Caddyfile >/dev/null 2>&1 || echo "warning: caddy reload failed (is caddy up?)"

umask 077
cat > "$secret" <<ENV
# Generated by new-product.sh. Do not commit.
DATABASE_URL=postgresql://$role:$pw@postgres:5432/$dbname
REDIS_URL=redis://$name:$rpw@redis:6379/$idx
PUBLIC_HOST=${name}-api.${DOMAIN}
ENV
echo "product '$name' ready: db=$dbname role=$role redis_db=$idx host=${name}-api.${DOMAIN} upstream=$upstream"
echo "secrets: infra/$secret (copy into the product's .env)"
